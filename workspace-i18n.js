function tr(ru, lang){
  const d = D[ru];
  if(d) return d[lang==='kk' ? 0 : 1];
  for(const [re, fn] of P){
    const m = ru.match(re);
    if(m){ const out = fn(m, lang); if(out!=null) return out; }
  }
  return null;
}

/* ---- applying it to the page ---- */
const CYR = /[А-Яа-яЁё]/;
const SKIP = 'script,style,textarea,[data-i18n-skip],[contenteditable="true"]';
const ATTRS = ['placeholder','title','aria-label'];
const textOrig = new WeakMap();   // text node → {orig, shown}
const attrOrig = new WeakMap();   // element → {attr: {orig, shown}}
let lang = 'ru', busy = false, observer = null;

function doText(node){
  const rec = textOrig.get(node);
  if(rec && node.nodeValue!==rec.shown) textOrig.delete(node);   // the page changed it — new original
  const r = textOrig.get(node);
  const orig = r ? r.orig : node.nodeValue;
  if(!CYR.test(orig)) return;
  const p = node.parentElement;
  if(!p || p.closest(SKIP)) return;
  // an <option> without value="" takes its value from its text — pin the
  // Russian value first, so translating the label never changes the data
  if(p.tagName==='OPTION' && !p.hasAttribute('value')) p.setAttribute('value', orig.trim());
  let shown = orig;
  if(lang!=='ru'){
    const key = orig.trim().replace(/\s+/g,' ');
    const t = key && tr(key, lang);
    if(t!=null){
      const lead = orig.match(/^\s*/)[0], tail = orig.match(/\s*$/)[0];
      shown = lead + t + tail;
    }
  }
  if(node.nodeValue!==shown) node.nodeValue = shown;
  if(shown!==orig) textOrig.set(node, {orig, shown}); else textOrig.delete(node);
}
function doAttrs(el){
  if(el.closest('[data-i18n-skip]')) return;
  let map = attrOrig.get(el);
  for(const a of ATTRS){
    if(!el.hasAttribute(a)) continue;
    const cur = el.getAttribute(a);
    let rec = map && map[a];
    if(rec && cur!==rec.shown){ delete map[a]; rec = null; }
    const orig = rec ? rec.orig : cur;
    if(!CYR.test(orig)) continue;
    let shown = orig;
    if(lang!=='ru'){ const t = tr(orig.trim().replace(/\s+/g,' '), lang); if(t!=null) shown = t; }
    if(cur!==shown) el.setAttribute(a, shown);
    if(shown!==orig){ if(!map){ map = {}; attrOrig.set(el, map); } map[a] = {orig, shown}; }
    else if(map) delete map[a];
  }
}
function walk(root){
  if(!root) return;
  if(root.nodeType===3){ doText(root); return; }
  if(root.nodeType!==1) return;
  if(root.matches && root.matches('script,style')) return;
  doAttrs(root);
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT|NodeFilter.SHOW_ELEMENT);
  let n;
  while((n = w.nextNode())){
    if(n.nodeType===3) doText(n);
    else if(n.nodeType===1) doAttrs(n);
  }
}
let titleOrig = null;
function apply(newLang){
  lang = newLang || 'ru';
  busy = true;
  try{
    walk(document.body);
    if(titleOrig==null) titleOrig = document.title;
    document.title = lang==='ru' ? titleOrig : L(lang, 'Régie — іс-шараның жұмыс үстелі', 'Régie — event workspace');
  } finally { busy = false; }
  if(!observer){
    observer = new MutationObserver(muts=>{
      if(busy || lang==='ru') return;
      busy = true;
      try{
        for(const m of muts){
          if(m.type==='childList') m.addedNodes.forEach(walk);
          else if(m.type==='characterData') doText(m.target);
          else if(m.type==='attributes') doAttrs(m.target);
        }
      } finally { busy = false; }
    });
    observer.observe(document.body, {subtree:true, childList:true, characterData:true, attributes:true, attributeFilter:ATTRS});
  }
}

